<?php

declare(strict_types=1);

namespace LiveUX\FileManagerBundle\Controller;

use DateTimeImmutable;
use League\Flysystem\FilesystemException;
use League\Flysystem\FilesystemOperator;
use LiveUX\FileManagerBundle\Config\ConfigProviderInterface;
use LiveUX\FileManagerBundle\Config\ProfileConfig;
use LiveUX\FileManagerBundle\Exception\AccessDeniedException;
use LiveUX\FileManagerBundle\Exception\FileManagerException;
use LiveUX\FileManagerBundle\Security\FileSecurityGuard;
use LiveUX\FileManagerBundle\Security\PathNormalizer;
use LiveUX\FileManagerBundle\Service\MessageTranslator;
use LiveUX\FileManagerBundle\Service\ShareLinkService;
use LiveUX\FileManagerBundle\Storage\VolumeRegistry;
use Symfony\Component\HttpFoundation\HeaderUtils;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpFoundation\StreamedResponse;
use Symfony\Component\HttpKernel\Exception\AccessDeniedHttpException;
use Symfony\Component\HttpKernel\Exception\BadRequestHttpException;
use Symfony\Component\HttpKernel\Exception\GoneHttpException;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;
use Symfony\Component\HttpKernel\Exception\ServiceUnavailableHttpException;
use Throwable;

/**
 * Serves files via cryptographically signed, expiring share URLs generated by ShareLinkService.
 * Hardened with Active-MIME sandbox headers, no-store cache headers, and noindex directives.
 */
final readonly class ShareController
{
    private const array ACTIVE_MIME_TYPES = [
        'text/html',
        'application/xhtml+xml',
        'text/javascript',
        'application/javascript',
        'application/x-javascript',
        'image/svg+xml',
        'text/xml',
        'application/xml',
    ];

    public function __construct(
        private ConfigProviderInterface $configProvider,
        private VolumeRegistry $volumeRegistry,
        private PathNormalizer $pathNormalizer,
        private ShareLinkService $shareLinkService,
        private FileSecurityGuard $fileSecurityGuard = new FileSecurityGuard(),
        private MessageTranslator $messageTranslator = new MessageTranslator(),
    ) {
    }

    public function __invoke(Request $request): Response
    {
        $q = $request->query->all();
        if (
            is_array($q['profile'] ?? null)
            || is_array($q['volume'] ?? null)
            || is_array($q['path'] ?? null)
            || is_array($q['inline'] ?? null)
            || is_array($q['v'] ?? null)
            || is_array($q['u'] ?? null)
            || is_array($q['d'] ?? null)
        ) {
            throw new BadRequestHttpException('Invalid query parameter.');
        }

        [$profile, $cleanPath, $locale] = $this->validateShareRequest($request);
        $volumeName = $q['volume'] ?? null;
        $volStr = is_string($volumeName) && $volumeName !== '' ? $volumeName : null;
        $inline = filter_var($q['inline'] ?? false, FILTER_VALIDATE_BOOL);

        try {
            $rawVolume = $this->volumeRegistry->getRawVolumeForProfile($profile, $volStr);
            $signedUser = $this->resolveSignedUserContext($request, $rawVolume);
            $signedDate = $this->resolveSignedDateContext($request, $rawVolume);
            $resolvedVolume = $this->volumeRegistry->getVolumeForProfileWithContext($profile, $rawVolume->name, $signedDate, $signedUser);
            if ($resolvedVolume->isLocalFilesystem() && ($resolvedVolume->path === null || $resolvedVolume->path === '' || !is_dir($resolvedVolume->path))) {
                throw new NotFoundHttpException($this->messageTranslator->trans('errors.file_not_found', [], $locale, 'File not found.'));
            }
            $filesystem = $this->volumeRegistry->getFilesystemWithContext($profile, $rawVolume->name, $signedDate, $signedUser);
        } catch (AccessDeniedException $e) {
            throw new AccessDeniedHttpException($this->messageTranslator->translateException($e, $locale), $e);
        } catch (FileManagerException $e) {
            throw new BadRequestHttpException($this->messageTranslator->translateException($e, $locale), $e);
        }

        try {
            if ($cleanPath === '' || !$filesystem->fileExists($cleanPath)) {
                throw new NotFoundHttpException($this->messageTranslator->trans('errors.file_not_found', [], $locale, 'File not found.'));
            }

            if (array_key_exists('v', $q)) {
                $expectedVersion = is_string($q['v']) ? $q['v'] : '';
                $actualVersion = $this->shareLinkService->computeFileVersionFingerprint($filesystem, $cleanPath);
                if (!hash_equals($actualVersion, $expectedVersion)) {
                    throw new GoneHttpException($this->messageTranslator->trans('errors.share_link_expired', [], $locale, 'This share link has expired.'));
                }
            }

            return $this->buildFileStreamResponse($request, $filesystem, $profile, $cleanPath, $inline, $resolvedVolume->isLocalFilesystem());
        } catch (FilesystemException $e) {
            throw new ServiceUnavailableHttpException(null, $this->messageTranslator->trans('errors.action_failed', [], $locale, 'Storage unavailable.'), $e);
        }
    }

    private function resolveSignedUserContext(Request $request, \LiveUX\FileManagerBundle\Config\VolumeConfig $rawVolume): ?string
    {
        if (!ShareLinkService::volumeUsesUserIdToken($rawVolume)) {
            return null;
        }

        $q = $request->query->all();
        $signedUser = $q['u'] ?? null;
        if (!is_string($signedUser) || trim($signedUser) === '' || preg_match('/^[a-zA-Z0-9_-]{1,128}$/', $signedUser) !== 1) {
            throw new AccessDeniedException('Invalid or missing tenant scope in share link.', 'errors.share_link_invalid');
        }

        return $signedUser;
    }

    private function resolveSignedDateContext(Request $request, \LiveUX\FileManagerBundle\Config\VolumeConfig $rawVolume): ?DateTimeImmutable
    {
        if (!ShareLinkService::volumeUsesDateTokens($rawVolume)) {
            return null;
        }

        $q = $request->query->all();
        $signedDate = $q['d'] ?? null;
        if (!is_string($signedDate) || preg_match('/^\d{4}-\d{2}-\d{2}$/', $signedDate) !== 1) {
            throw new AccessDeniedException('Invalid or missing date scope in share link.', 'errors.share_link_invalid');
        }

        $parsed = DateTimeImmutable::createFromFormat('!Y-m-d', $signedDate);
        if ($parsed === false || $parsed->format('Y-m-d') !== $signedDate) {
            throw new AccessDeniedException('Invalid date scope in share link.', 'errors.share_link_invalid');
        }

        return $parsed;
    }

    /**
     * @return array{0: ProfileConfig, 1: string, 2: string}
     */
    private function validateShareRequest(Request $request): array
    {
        $q = $request->query->all();
        $profileName = is_string($q['profile'] ?? null) ? $q['profile'] : 'default';
        $rawPath = is_string($q['path'] ?? null) ? $q['path'] : '';
        $profile = null;

        try {
            // Verify HMAC signature & expiration BEFORE looking up profile to prevent profile enumeration.
            $this->shareLinkService->assertValidSignedRequest($request);

            $profile = $this->configProvider->getProfile($profileName);
            $locale = $this->messageTranslator->resolveLocale($request, $profile);

            if (!$this->shareLinkService->isAvailableForProfile($profile)) {
                throw new AccessDeniedException('Signed share links are disabled for this profile.', 'errors.share_disabled');
            }

            $cleanPath = $this->pathNormalizer->normalize($rawPath);
            $this->fileSecurityGuard->assertAccessiblePath($cleanPath, $profile);
            $this->fileSecurityGuard->assertSafeFilename(PathNormalizer::basenameUtf8($cleanPath));

            return [$profile, $cleanPath, $locale];
        } catch (AccessDeniedException $e) {
            $locale = $this->messageTranslator->resolveLocale($request, $profile);

            throw new AccessDeniedHttpException($this->messageTranslator->translateException($e, $locale), $e);
        } catch (FileManagerException $e) {
            $locale = $this->messageTranslator->resolveLocale($request, $profile);
            if ($e->getCode() === Response::HTTP_GONE) {
                throw new GoneHttpException($this->messageTranslator->translateException($e, $locale), $e);
            }

            throw new BadRequestHttpException($this->messageTranslator->translateException($e, $locale), $e);
        }
    }

    private function buildFileStreamResponse(
        Request $request,
        FilesystemOperator $filesystem,
        ProfileConfig $profile,
        string $cleanPath,
        bool $inline,
        bool $isLocal,
    ): StreamedResponse {
        try {
            $mimeType = $filesystem->mimeType($cleanPath);
        } catch (Throwable) {
            $mimeType = 'application/octet-stream';
        }
        try {
            $fileSize = $filesystem->fileSize($cleanPath);
        } catch (Throwable) {
            $fileSize = -1;
        }

        $filename = PathNormalizer::basenameUtf8($cleanPath);
        $response = $this->createRangedStreamResponse($request, $filesystem, $cleanPath, $fileSize, $isLocal);
        $response->headers->set('X-Content-Type-Options', 'nosniff');
        $response->headers->set('Referrer-Policy', 'no-referrer');
        $response->headers->set('Cache-Control', 'private, no-store, max-age=0');
        $response->headers->set('X-Robots-Tag', 'noindex, nofollow');

        if ($response->getStatusCode() === Response::HTTP_REQUESTED_RANGE_NOT_SATISFIABLE) {
            $response->headers->set('Content-Security-Policy', "default-src 'none'");

            return $response;
        }

        $effectiveMime = $mimeType !== '' ? $mimeType : 'application/octet-stream';
        if (preg_match('/^[a-z0-9!#$&^_.+-]+\/[a-z0-9!#$&^_.+-]+$/i', trim(explode(';', $effectiveMime, 2)[0])) !== 1) {
            $effectiveMime = 'application/octet-stream';
        }
        $lowerMime = trim(explode(';', strtolower($effectiveMime), 2)[0]);
        $ext = PathNormalizer::extensionUtf8($filename);
        $forceAttachment = in_array($lowerMime, self::ACTIVE_MIME_TYPES, true)
            || $ext === 'svg'
            || $ext === 'svgz'
            || str_contains($lowerMime, 'svg')
            || str_contains($lowerMime, 'xml')
            || str_contains($lowerMime, 'html')
            || str_contains($lowerMime, 'script');
        $allowInline = ($profile->share['allow_inline_preview'] ?? true) === true;
        $previewDisabledByConfig = ($lowerMime === 'application/pdf' && ($profile->ui['allow_pdf_preview'] ?? true) === false)
            || (str_starts_with($lowerMime, 'video/') && ($profile->ui['allow_video_preview'] ?? true) === false);
        $disposition = ($inline && $allowInline && !$forceAttachment && !$previewDisabledByConfig && $this->isInlinePreviewableMime($lowerMime))
            ? HeaderUtils::DISPOSITION_INLINE
            : HeaderUtils::DISPOSITION_ATTACHMENT;

        $asciiFallback = preg_replace('/[^\x20-\x7E]/', '_', $filename) ?: 'download';
        $asciiFallback = str_replace(['/', '\\', '"', '%'], '_', $asciiFallback);

        $safeContentType = $lowerMime === 'text/plain' ? 'text/plain; charset=UTF-8' : $lowerMime;
        $response->headers->set('Content-Type', $safeContentType);
        $response->headers->set('Content-Disposition', HeaderUtils::makeDisposition($disposition, $filename, $asciiFallback));
        $isInlinePdf = $disposition === HeaderUtils::DISPOSITION_INLINE && $lowerMime === 'application/pdf';
        $response->headers->set(
            'Content-Security-Policy',
            $isInlinePdf
                ? "default-src 'self'; script-src 'none'; style-src 'self' 'unsafe-inline'; object-src 'self'; frame-ancestors 'self'"
                : "default-src 'none'; sandbox",
        );

        return $response;
    }

    private function createRangedStreamResponse(
        Request $request,
        FilesystemOperator $filesystem,
        string $cleanPath,
        int $fileSize,
        bool $isLocal,
    ): StreamedResponse {
        $rangeHeader = $request->headers->get('Range');
        if ($isLocal && $fileSize > 0 && is_string($rangeHeader) && $rangeHeader !== '') {
            $parsedRange = \LiveUX\FileManagerBundle\Util\HttpByteRangeParser::parseSingleByteRange($rangeHeader, $fileSize);
            if ($parsedRange['status'] === 'invalid') {
                $invalid = new StreamedResponse(static function (): void {});
                $invalid->setStatusCode(Response::HTTP_REQUESTED_RANGE_NOT_SATISFIABLE);
                $invalid->headers->set('Content-Range', sprintf('bytes */%d', $fileSize));
                $invalid->headers->set('Accept-Ranges', 'bytes');

                return $invalid;
            }
            if ($parsedRange['status'] === 'ok') {
                $start = $parsedRange['start'];
                $end = $parsedRange['end'];
                $length = ($end - $start) + 1;
                $partial = new StreamedResponse(static function () use ($filesystem, $cleanPath, $start, $length): void {
                    $stream = $filesystem->readStream($cleanPath);
                    if (!is_resource($stream)) {
                        return;
                    }
                    try {
                        \LiveUX\FileManagerBundle\Util\HttpByteRangeParser::echoStreamRange($stream, $start, $length);
                    } finally {
                        fclose($stream);
                    }
                }, Response::HTTP_PARTIAL_CONTENT);
                $partial->headers->set('Accept-Ranges', 'bytes');
                $partial->headers->set('Content-Range', sprintf('bytes %d-%d/%d', $start, $end, $fileSize));
                $partial->headers->set('Content-Length', (string) $length);

                return $partial;
            }
        }

        $response = new StreamedResponse(static function () use ($filesystem, $cleanPath): void {
            $stream = $filesystem->readStream($cleanPath);
            if (!is_resource($stream)) {
                return;
            }
            try {
                fpassthru($stream);
            } finally {
                fclose($stream);
            }
        });
        if ($fileSize >= 0) {
            $response->headers->set('Content-Length', (string) $fileSize);
        }
        if ($isLocal && $fileSize > 0) {
            $response->headers->set('Accept-Ranges', 'bytes');
        }

        return $response;
    }

    private function isInlinePreviewableMime(string $lowerMime): bool
    {
        if (in_array($lowerMime, self::ACTIVE_MIME_TYPES, true)) {
            return false;
        }

        return str_starts_with($lowerMime, 'image/')
            || str_starts_with($lowerMime, 'video/')
            || str_starts_with($lowerMime, 'audio/')
            || $lowerMime === 'application/pdf'
            || $lowerMime === 'text/plain';
    }
}
